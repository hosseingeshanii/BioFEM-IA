"""case.json: a case's options grouped by topic, translated to the PETSc options file (control.dat) the solvers read.

    {
      "model": "solid3d",                       # shell (default) | solid3d
      "description": "free text",               # not passed to the solver
      "geometry":   {"problem": "lv", "dm_plex_filename": "pz3d.msh"},
      "material":   {"ho_tension_only": true},
      "activation": {"gamma": 0.2},
      "fibers":     {"alpha_endo": -60, "alpha_epi": 60},
      "bcs":        {},
      "pressure":   {},
      "time":       {"steps": 100},
      "solver":     {"snes_rtol": 1e-8, "pc_type": "lu"},
      "output":     {"out_dir": "out", "out_every": 5}
    }

Every key inside a section is a solver option name without the leading '-'. Values: a number or string gives
"-key value"; true gives the bare flag "-key"; false leaves the option out; a list gives "-key a,b,c".
Integer switches of the shell (e.g. "membrane": 1) stay integers. Keys starting with '_' are comments.
The section names only organise the file: any option may sit in any section.
"""
import json
import re
import sys
from pathlib import Path

SECTIONS = ["geometry", "material", "activation", "fibers", "bcs", "pressure", "time", "solver", "output", "other"]
TOP_LEVEL = {"model", "description"}
HEADER = "# generated by biofem from case.json -- edit case.json, not this file"

# option-name rules used by `biofem case convert` to sort an existing control.dat into sections (first match wins)
_RULES = [
    ("solver",     r"^(snes_|ksp_|pc_|fieldsplit_|fem_snes|fem_ksp|fem_pc|mat_|jacpc_|C33_|log_c33|num_gaussian|"
                   r"adaptive_substeps|substep_levels|explicit$|timeinteg$|newmark_|damping$|dampfactor$|disable_fdyn$|"
                   r"options_left$)"),
    ("output",     r"^(out_|write_|vtk_|tiout$|monitor_|debug_|log_view)"),
    ("bcs",        r"^(lv_fix_|lv_base_tangent|lv_rigid|lv_mean_bc|fix_|null_avg|pin)"),
    ("pressure",   r"(pressure|^p_cav|^p_ed|^p_es|^volume)"),
    ("activation", r"(gamma|^muscle_act|^fa_|^act_|_act_coeff|^curv_based_act|^fiber_based_act)"),
    ("fibers",     r"^(alpha_|beta_|lv_alpha|cart_fib|fib|twist)"),
    ("material",   r"^(ho_|E$|mu$|K$|rho$|h0$|nu$|bulk_modulus$|Constitutive|material_model|membrane$|bending$|traction$)"),
    ("geometry",   r"^(dm_plex|dm_|lv_|mesh|in_dir$|char_length|problem$|nitti_|nbody$|twod$|contact$|inverse$)"),
    ("time",       r"^(steps$|dt$|tisteps$|tistart$|t_|legacy_restart)"),
]


def load_case(path):
    case = json.loads(Path(path).read_text())
    if not isinstance(case, dict):
        sys.exit(f"error: {path}: top level must be an object")
    unknown = [k for k in case if k not in TOP_LEVEL and k not in SECTIONS and not k.startswith("_")]
    if unknown:
        sys.exit(f"error: {path}: unknown section(s) {unknown}; sections are {SECTIONS}")
    model = case.get("model", "shell")
    if model not in ("shell", "solid3d"):
        sys.exit(f"error: {path}: model must be shell or solid3d, not {model!r}")
    return case


def case_options(case):
    """[(section, '-key value' or '-key')] in section order; checks that no option is given twice."""
    out, seen = [("model", f"-model {case.get('model', 'shell')}")], {}
    for sec in SECTIONS:
        for key, val in (case.get(sec) or {}).items():
            if key.startswith("_"):
                continue
            key = key.lstrip("-")
            if key in seen:
                sys.exit(f"error: option '{key}' given in both '{seen[key]}' and '{sec}'")
            seen[key] = sec
            if val is False:
                continue
            if val is True or val is None:
                out.append((sec, f"-{key}"))
            elif isinstance(val, list):
                out.append((sec, f"-{key} {','.join(str(v) for v in val)}"))
            else:
                out.append((sec, f"-{key} {val}"))
    return out


def write_control(case, path, source="case.json"):
    lines, last = [HEADER, f"# source: {source}"], None
    if case.get("description"):
        lines.append(f"# {case['description']}")
    for sec, opt in case_options(case):
        if sec != last:
            lines.append(f"\n# {sec}")
            last = sec
        lines.append(opt)
    Path(path).write_text("\n".join(lines) + "\n")


def is_generated(control_path):
    p = Path(control_path)
    return p.exists() and p.read_text(errors="replace").startswith(HEADER)


def _parse_value(tok):
    for conv in (int, float):
        try:
            return conv(tok)
        except ValueError:
            pass
    return tok


def control_to_case(control_path):
    """Sort a hand-written control.dat into case.json sections (the comments are not kept)."""
    toks = [t for line in Path(control_path).read_text(errors="replace").splitlines()
            if not line.lstrip().startswith("#") for t in line.split("#")[0].split()]
    case = {"model": "shell"}
    i = 0
    while i < len(toks):
        if not toks[i].startswith("-") or re.match(r"^-\d", toks[i]):
            sys.exit(f"error: {control_path}: expected an option, got {toks[i]!r}")
        key = toks[i][1:]
        if i + 1 < len(toks) and (not toks[i + 1].startswith("-") or re.match(r"^-[\d.]", toks[i + 1])):
            val, i = _parse_value(toks[i + 1]), i + 2
        else:
            val, i = True, i + 1
        if key == "model":
            case["model"] = val
            continue
        sec = next((s for s, rx in _RULES if re.search(rx, key)), "other")
        if key in case.get(sec, {}):
            print(f"[biofem] warning: -{key} is given twice ({case[sec][key]!r}, then {val!r}); keeping the last, "
                  "as PETSc does", file=sys.stderr)
        case.setdefault(sec, {})[key] = val
    return {k: case[k] for k in ["model"] + SECTIONS if k in case}


def cmd_case(args):
    if args.case_command == "convert":
        src, dst = Path(args.control), Path(args.out)
        if dst.exists() and not args.force:
            sys.exit(f"error: {dst} exists (use --force to overwrite)")
        case = control_to_case(src)
        dst.write_text(json.dumps(case, indent=2) + "\n")
        n = sum(len(v) for k, v in case.items() if isinstance(v, dict))
        print(f"[biofem] {src} -> {dst}: {n} options in sections " + ", ".join(k for k in case if k != "model"))
        print("         check the 'other' section, then `biofem case write` regenerates control.dat from it")
    elif args.case_command == "show":
        for sec, opt in case_options(load_case(args.case)):
            print(f"{sec:>10}  {opt}")
    elif args.case_command == "write":
        ctrl = Path(args.case).parent / "control.dat"
        if ctrl.exists() and not is_generated(ctrl) and not args.force:
            sys.exit(f"error: {ctrl} was not generated from case.json; keep it with `biofem case convert` first, "
                     "or pass --force to overwrite it")
        write_control(load_case(args.case), ctrl, Path(args.case).name)
        print(f"[biofem] wrote {ctrl}")
